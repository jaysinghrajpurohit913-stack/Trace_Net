"""Drafts of LAWFUL information requests. TraceNet only writes the draft; the investigating officer signs and sends it
under the applicable legal process. Subscriber, login, payment and other non-public records are NEVER fetched by this tool.

Each draft names: the identifier (IP / domain / account), the EXACT timestamp with time zone (local + UTC) and the window.
"""
from __future__ import annotations

import pandas as pd

from .. import config as C
from .timeutil import fmt_both

HEADER = ("To: The Nodal / Compliance Officer, {to}\nFrom: [Investigating Officer, Police Station / Cyber Cell]\nDate: [date]\n"
          "Ref: [FIR / NCRP acknowledgement no.: {ref}]\nSubject: Request for information under applicable law - {subject}\n")
LEGAL = ("This request is made under [applicable legal provision - to be filled in by the Investigating Officer]. "
         "Kindly preserve the records mentioned below and furnish them to the undersigned. Please do not inform the account holder / customer.\n")
FOOT = ("\nPlease share the records in a readable electronic format (CSV / Excel / PDF) with a covering certificate.\n"
        "Regards,\n[Name, rank, designation, contact]\n"
        "\n(Draft generated by TraceNet from the data supplied. Indicative technical details such as IP geolocation or hosting provider are leads, not proof of identity.)\n")


def _window(ts, before=15, after=15):
    ts = pd.Timestamp(ts)
    return f"{(ts - pd.Timedelta(minutes=before)):%d %b %Y %H:%M} to {(ts + pd.Timedelta(minutes=after)):%H:%M}"


def registrar_request(domain, registrar, complaint_ids, first_seen=None, ips=()):
    body = [HEADER.format(to=registrar or "Domain Registrar", ref=", ".join(complaint_ids) or "[ ]", subject=f"domain {domain}"), LEGAL,
            f"Domain: {domain}", f"Related IP address(es): {', '.join(ips) or '[not known]'}",
            (f"First observed in the complaint(s): {fmt_both(first_seen)}" if first_seen is not None and pd.notna(first_seen) else "First observed: [date and time with time zone]"),
            "\nRecords requested:",
            "1. Registrant, administrative and technical contact details (as provided at registration) and their verification status.",
            "2. Date, time (with time zone) and IP address of the registration, every renewal and every change of name servers / contacts.",
            "3. Payment records for the domain (mode, payer details, transaction reference).",
            "4. Account(s) used to manage the domain: account id, e-mail, phone, login IP addresses with exact timestamps for the last [90] days.",
            "5. Other domains registered from the same account, payment instrument, e-mail or phone.",
            "6. Please place the domain on hold / suspend DNS resolution if permitted by your policy and applicable law."]
    return "\n".join(body) + FOOT


def hosting_request(provider, ip, domains, ts=None, complaint_ids=(), asn=""):
    when = (f"{fmt_both(ts)}  (window {_window(ts)} local time)" if ts is not None and pd.notna(ts) else "[exact date, time and time zone]")
    body = [HEADER.format(to=provider or "Hosting / Cloud Provider", ref=", ".join(complaint_ids) or "[ ]", subject=f"IP address {ip}"), LEGAL,
            f"IP address: {ip}" + (f"  ({asn})" if asn else ""), f"Domain(s) hosted: {', '.join(domains) or '[ ]'}", f"Date / time of interest: {when}",
            "\nRecords requested:",
            "1. Customer account that was assigned this IP address at the time above: name, billing address, e-mail, phone, KYC documents.",
            "2. Date the service / server was created, plan, payment records (mode, payer, transaction reference).",
            "3. Login / access logs of the customer account and the server (control panel, SSH/RDP, API) with IP addresses and exact timestamps.",
            "4. Any other servers, IPs or domains under the same customer account or payment instrument.",
            "5. Preserve server images / logs and suspend the service if permitted."]
    return "\n".join(body) + FOOT


def isp_request(isp, ip, ts, complaint_ids=(), port=""):
    body = [HEADER.format(to=isp or "Internet Service Provider / Telecom Operator", ref=", ".join(complaint_ids) or "[ ]", subject=f"subscriber of IP {ip} at a given time"), LEGAL,
            f"IP address: {ip}" + (f"   Source port: {port}" if port else "   Source port: [please state if available - needed for shared / CGNAT addresses]"),
            f"Exact date and time: {fmt_both(ts)}" if ts is not None and pd.notna(ts) else "Exact date and time: [with time zone]",
            "\nRecords requested:",
            "1. Subscriber details (name, address, connection id, KYC) to whom this IP (and port, if shared) was assigned at that exact time, with the assignment start and end times.",
            "2. Type of connection (fixed / mobile / public Wi-Fi) and the location of the connection.",
            "3. Please note that dynamic and shared IPs can serve many users; kindly confirm the mapping using your NAT / DHCP logs."]
    return "\n".join(body) + FOOT


def drafts_for(intel, ips: pd.DataFrame, corr: pd.DataFrame, complaint_ids=None) -> list[dict]:
    """All provider letters that the data supports -> [{kind, to, subject, text}]."""
    out = []
    d = intel.domains
    if complaint_ids is not None:
        d = d[d.complaint_id.map(lambda x: not x or bool(set(map(str.strip, x.split(","))) & set(complaint_ids)))]
    for dom, g in d[d.domain != ""].groupby("domain"):
        r = g.iloc[0]
        out.append(dict(kind="registrar", to=r.registrar or "Registrar (unknown - look up RDAP first)", subject=dom,
                        text=registrar_request(dom, r.registrar, sorted({c for c in g.complaint_id if c}), g.first_seen.min(), sorted({x for x in g.ip if x}))))
    ipx = ips.set_index("ip") if len(ips) else pd.DataFrame(columns=["org", "asn"]).set_index("ip")
    for ip, g in d[d.ip != ""].groupby("ip"):
        org = ipx.org.get(ip, "") if ip in ipx.index else ""
        asn = ipx.asn.get(ip, "") if ip in ipx.index else ""
        out.append(dict(kind="hosting", to=org or "Hosting provider (unknown)", subject=ip,
                        text=hosting_request(org, ip, sorted({x for x in g.domain if x}), g.first_seen.min(), sorted({c for c in g.complaint_id if c}), asn)))
    if len(corr):
        for ip, g in corr[corr["class"] != "far"].groupby("ip"):
            org = ipx.org.get(ip, "") if ip in ipx.index else ""
            r = g.iloc[0]
            out.append(dict(kind="isp", to=org or "ISP / telecom operator of the IP", subject=f"{ip} @ {r.when_local:%d %b %H:%M}",
                            text=isp_request(org, ip, r.when_local)))
    return out
